drop table if exists customers;
drop table if exists products;
drop table if exists orders;
drop table if exists order_lines;
drop table if exists shipments;
drop table if exists shipment_events;
drop table if exists tickets;
drop table if exists refunds;
drop table if exists outbox;
drop table if exists restock_requests;
drop table if exists store_credits;
drop table if exists exchanges;
drop table if exists manager_queue;
create table customers (id int primary key, name text, email text, phone text, city text, tier text, card_number text, joined date);
create table products (sku text primary key, name text, category text, price numeric, stock int, reorder_point int, incoming_qty int, incoming_date date);
create table orders (id int primary key, customer_id int, status text, created date, shipped date, delivered date, ship_address text, total numeric, refunded numeric);
create table order_lines (order_id int, sku text, qty int, price numeric);
create table shipments (order_id int primary key, carrier text, tracking text, status text, eta date);
create table shipment_events (order_id int, at text, description text);
create table tickets (id text primary key, customer_id int, order_id int, subject text, description text, priority text, status text, created date, notes text);
create table refunds (id serial primary key, order_id int, amount numeric, reason text, created date);
create table outbox (id serial primary key, customer_id int, email text, subject text, body text, created date);
create table restock_requests (id serial primary key, sku text, quantity int, note text, created date);
create table store_credits (id serial primary key, customer_id int, amount numeric, reason text, approved_by text, created date);
create table exchanges (id serial primary key, order_id int, sku text, size text, created date);
create table manager_queue (handle text primary key, tool text, customer_id int, amount numeric, reason text, created date);
