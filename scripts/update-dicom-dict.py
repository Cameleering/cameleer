#!/usr/bin/env python3
"""Regenerate the DICOM data dictionary, UID registry and de-identification tables of
crates/cameleer-dicom from the DICOM standard's DocBook XML.

Sources (DICOM standard, NEMA, edition pinned below):
  PS3.6  Data Dictionary   Tables 6-1, 7-1, 8-1, 9-1 (data elements) and A-1 (UIDs)
  PS3.7  Message Exchange  Tables E.1-1 and E.2-1 (command elements of group 0000)
  PS3.15 Security          Table E.1-1 (Application Level Confidentiality Profile Attributes)

The script checks that each document names the pinned edition in its subtitle and that its
SHA-256 matches the pinned digest. Any mismatch aborts without writing.

To update to a new edition: set EDITION, run `python3 scripts/update-dicom-dict.py
--print-digest`, put the printed digests in DIGESTS, run the script again, then run
`cargo test -p cameleer-dicom`. NEMA serves the current edition under /current/ and earlier
editions under /<edition>/; set BASE to the archived URL once the edition is archived.
`--source DIR` reads part06.xml, part07.xml and part15.xml from DIR instead of downloading.

Output (committed; never edit by hand):
  crates/cameleer-dicom/src/dict_data.rs   - data elements and UIDs (module `dict::data`)
  crates/cameleer-dicom/src/deid_table.rs  - PS3.15 Table E.1-1 (module `dict::deid`)
Standard library only.
"""

import hashlib
import os
import sys
import urllib.request
import xml.etree.ElementTree as ET

EDITION = "2026d"
BASE = "https://dicom.nema.org/medical/dicom/current/source/docbook"
PARTS = {"part06": "PS3.6", "part07": "PS3.7", "part15": "PS3.15"}
DIGESTS = {
    "part06": "fa9f0f8d67eba692dcf95cfeae0a8f4e071beeb7844215a860bc4b9d5dfaad25",
    "part07": "979da8b222a47d80260a5463ad1c2767bcc7966b6c5c2893daefedbd6c99b3df",
    "part15": "1eb2a9724822476b3f1f3de23d15ae655a4c7f6e9d32bf16f2d9ef76d7d8437c",
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "cameleer-dicom", "src")
D = "{http://docbook.org/ns/docbook}"
XML_ID = "{http://www.w3.org/XML/1998/namespace}id"

VRS = ["AE", "AS", "AT", "CS", "DA", "DS", "DT", "FL", "FD", "IS", "LO", "LT", "OB", "OD", "OF",
       "OL", "OV", "OW", "PN", "SH", "SL", "SQ", "SS", "ST", "SV", "TM", "UC", "UI", "UL", "UN",
       "UR", "US", "UT", "UV"]

UID_KINDS = {
    "SOP Class": "SopClass",
    "Transfer Syntax": "TransferSyntax",
    "Meta SOP Class": "MetaSopClass",
    "Well-known SOP Instance": "WellKnownSopInstance",
    "Application Context Name": "ApplicationContextName",
    "Coding Scheme": "CodingScheme",
}

HEADER = """// GENERATED by scripts/update-dicom-dict.py from the DICOM standard {edition}
// ({sources}). Do not edit by hand: change the script and rerun it.
"""


def load(name, source_dir, print_digest):
    if source_dir:
        with open(os.path.join(source_dir, name + ".xml"), "rb") as f:
            data = f.read()
    else:
        url = f"{BASE}/{name}/{name}.xml"
        print(f"fetching {url}", file=sys.stderr)
        with urllib.request.urlopen(url, timeout=120) as r:
            data = r.read()
    digest = hashlib.sha256(data).hexdigest()
    if print_digest:
        print(f'    "{name}": "{digest}",')
        return None
    if digest != DIGESTS[name]:
        sys.exit(f"{name}.xml: SHA-256 {digest} does not match the pinned {DIGESTS[name]}")
    root = ET.fromstring(data)
    subtitle = "".join(next(root.iter(D + "subtitle")).itertext())
    if f"{PARTS[name]} {EDITION}" not in subtitle:
        sys.exit(f"{name}.xml: expected edition {EDITION}, found {subtitle!r}")
    return root


def table(root, tid):
    for t in root.iter(D + "table"):
        if t.get(XML_ID) == tid:
            return t
    sys.exit(f"table {tid} not found")


def rows(t):
    out = []
    for tr in t.iter(D + "tr"):
        out.append(["".join(c.itertext()).strip().replace("​", "") for c in tr])
    return out[1:]  # header row


def parse_tag(s):
    """'(60xx,3000)' -> (tag, mask) with x digits zero in both."""
    s = s.strip().strip("()")
    g, e = s.split(",")
    hexs = (g + e).upper()
    tag = mask = 0
    for ch in hexs:
        tag <<= 4
        mask <<= 4
        if ch != "X":
            tag |= int(ch, 16)
            mask |= 0xF
    return tag, mask


def vr_pair(text):
    parts = [p.strip() for p in text.split(" or ")]
    vr = VRS.index(parts[0])
    alt = VRS.index(parts[1]) if len(parts) > 1 else 255
    return vr, alt


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def blob(name, parts):
    """A `&str` blob built from chunks of about 100 characters, with (offset << 8 | len) refs."""
    refs = {}
    chunks, cur, off = [], "", 0
    for p in parts:
        if p in refs:
            continue
        n = len(p.encode("utf-8"))
        assert n < 256, p
        refs[p] = (off << 8) | n
        off += n
        cur += p
        if len(cur) > 100:
            chunks.append(cur)
            cur = ""
    if cur:
        chunks.append(cur)
    lines = [f"pub static {name}: &str = concat!("]
    lines += [f"    {rs(c)}," for c in chunks]
    lines.append(");")
    return refs, "\n".join(lines)


def elements(p6, p7):
    out = {}
    for tid in ("table_6-1", "table_7-1", "table_8-1", "table_9-1"):
        for r in rows(table(p6, tid)):
            tag, name, kw, vr, vm, ret = r[:6]
            if not kw or vr in ("", "See Note"):
                continue  # retired placeholders without data; items and delimiters (FFFE,xxxx)
            out[parse_tag(tag)] = (kw, name, vr, vm, ret.startswith("RET"))
    for tid, retired in (("table_E.1-1", False), ("table_E.2-1", True)):
        for r in rows(table(p7, tid)):
            tag, name, kw, vr, vm = r[:5]
            if not kw or not vr:
                continue
            out[parse_tag(tag)] = (kw, name, vr, vm, retired)
    return out


def write_dict(p6, p7):
    els = elements(p6, p7)
    exact = sorted((t, v) for (t, m), v in els.items() if m == 0xFFFFFFFF)
    # most specific masks first
    masked = sorted(((t, m), v) for (t, m), v in els.items() if m != 0xFFFFFFFF)
    masked.sort(key=lambda e: -bin(e[0][1]).count("1"))
    vms = sorted({v[3] for v in els.values()})
    kw_refs, kw_blob = blob("KEYWORDS", [v[0] for _, v in exact] + [v[0] for _, v in masked])
    name_refs, name_blob = blob("NAMES", [v[1] for _, v in exact] + [v[1] for _, v in masked])

    def el(tag, mask, v):
        kw, name, vr, vm, ret = v
        a, b = vr_pair(vr)
        return (f"    e(0x{tag:08X}, 0x{mask:08X}, 0x{kw_refs[kw]:X}, 0x{name_refs[name]:X}, "
                f"{a}, {b}, {vms.index(vm)}, {str(ret).lower()}),")

    all_kw = [v[0] for _, v in exact] + [v[0] for _, v in masked]
    kw_index = sorted(range(len(all_kw)), key=lambda i: all_kw[i])
    assert len(all_kw) < 65536

    uids = []
    for r in rows(table(p6, "table_A-1")):
        uid, name, kw, kind = r[:4]
        uids.append((uid, name, kw, UID_KINDS.get(kind, "Other"), "(Retired)" in name))
    uids.sort()

    src = [HEADER.format(edition=EDITION, sources="PS3.6 Tables 6-1, 7-1, 8-1, 9-1 and A-1; PS3.7 Tables E.1-1 and E.2-1")]
    src.append("#![allow(clippy::all)]\n")
    src.append("use super::UidKind;\n")
    src.append(f'/// The edition of the standard these tables come from.\npub const EDITION: &str = "{EDITION}";\n')
    src.append("/// A packed data element: `kw` and `name` are `offset << 8 | len` into [`KEYWORDS`] and\n"
               "/// [`NAMES`]; `vr` and `alt` index `crate::vr::ALL` (255 = no second VR); `vm` indexes [`VMS`].")
    src.append("#[derive(Clone, Copy)]\npub struct E {\n    pub tag: u32,\n    pub mask: u32,\n    pub kw: u32,\n"
               "    pub name: u32,\n    pub vr: u8,\n    pub alt: u8,\n    pub vm: u8,\n    pub retired: bool,\n}\n")
    src.append("#[allow(clippy::too_many_arguments)]\n"
               "const fn e(tag: u32, mask: u32, kw: u32, name: u32, vr: u8, alt: u8, vm: u8, retired: bool) -> E {\n"
               "    E { tag, mask, kw, name, vr, alt, vm, retired }\n}\n")
    src.append(kw_blob + "\n")
    src.append(name_blob + "\n")
    src.append("pub static VMS: &[&str] = &[" + ", ".join(rs(v) for v in vms) + "];\n")
    src.append(f"/// Plain tags, sorted by tag ({len(exact)}).\npub static ELEMENTS: &[E] = &[")
    src += [el(t, 0xFFFFFFFF, v) for t, v in exact]
    src.append("];\n")
    src.append(f"/// Repeating groups and ranges, most specific first ({len(masked)}).\npub static MASKED: &[E] = &[")
    src += [el(t, m, v) for (t, m), v in masked]
    src.append("];\n")
    src.append("/// Indices into `ELEMENTS` followed by `MASKED`, sorted by keyword.\npub static KEYWORD_INDEX: &[u16] = &[")
    for i in range(0, len(kw_index), 20):
        src.append("    " + ", ".join(str(x) for x in kw_index[i:i + 20]) + ",")
    src.append("];\n")
    src.append(f"/// The UID registry, sorted by UID ({len(uids)}): uid, name, keyword, kind, retired.")
    src.append("pub static UIDS: &[(&str, &str, &str, UidKind, bool)] = &[")
    for uid, name, kw, kind, ret in uids:
        src.append(f"    ({rs(uid)}, {rs(name)}, {rs(kw)}, UidKind::{kind}, {str(ret).lower()}),")
    src.append("];")
    path = os.path.join(OUT, "dict_data.rs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(src) + "\n")
    print(f"wrote {path}: {len(exact)} elements, {len(masked)} masked, {len(uids)} UIDs", file=sys.stderr)


def write_deid(p15):
    out = []
    for r in rows(table(p15, "table_E.1-1")):
        name, tag = r[0], r[1]
        codes = r[4:15]
        if tag.startswith("(gggg,eeee)"):
            # all private attributes: any odd group, written as a mask on the group's low bit
            t, m = 0x00010000, 0x00010000
        else:
            t, m = parse_tag(tag)
        out.append((t, m, name, codes))
    fields = ["basic", "retain_safe_private", "retain_uids", "retain_device_identity",
              "retain_institution_identity", "retain_patient_characteristics", "retain_long_full_dates",
              "retain_long_modified_dates", "clean_descriptors", "clean_structured_content", "clean_graphics"]
    src = [HEADER.format(edition=EDITION, sources="PS3.15 Table E.1-1")]
    src.append("//! PS3.15 Table E.1-1, Application Level Confidentiality Profile Attributes.\n//!\n"
               "//! A row applies to a tag when `tag & mask == row.tag & mask`. The `xx` digits of repeating\n"
               "//! groups such as `(50xx,xxxx)` are cleared in `mask`. The row `(gggg,eeee) where gggg is odd`\n"
               "//! (every private attribute) has `tag` and `mask` 0x0001_0000: it matches any odd group.\n"
               "//! Action codes are kept exactly as in the standard (`X`, `Z`, `D`, `K`, `C`, `U`, `X/Z`,\n"
               "//! `X/D`, `X/Z/D`, `Z/D`, `X/Z/U*`); an empty cell is `\"\"`.\n")
    src.append(f'/// The edition of the standard this table comes from.\npub const EDITION: &str = "{EDITION}";\n')
    src.append("/// One row of Table E.1-1: the action of the Basic Profile and of each option.")
    src.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct DeidRow {\n    pub tag: u32,\n    pub mask: u32,\n    pub name: &'static str,")
    src += [f"    pub {f}: &'static str," for f in fields]
    src.append("}\n")
    src.append("const fn d(tag: u32, mask: u32, name: &'static str, c: [&'static str; 11]) -> DeidRow {")
    src.append("    DeidRow {\n        tag,\n        mask,\n        name,")
    src += [f"        {f}: c[{i}]," for i, f in enumerate(fields)]
    src.append("    }\n}\n")
    src.append(f"/// The rows, in the standard's order ({len(out)}).\npub static ROWS: &[DeidRow] = &[")
    for t, m, name, codes in out:
        src.append(f"    d(0x{t:08X}, 0x{m:08X}, {rs(name)}, [" + ", ".join(rs(c) for c in codes) + "]),")
    src.append("];")
    path = os.path.join(OUT, "deid_table.rs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(src) + "\n")
    print(f"wrote {path}: {len(out)} rows", file=sys.stderr)


def main():
    args = sys.argv[1:]
    print_digest = "--print-digest" in args
    source_dir = None
    if "--source" in args:
        source_dir = args[args.index("--source") + 1]
    docs = {name: load(name, source_dir, print_digest) for name in PARTS}
    if print_digest:
        return
    write_dict(docs["part06"], docs["part07"])
    write_deid(docs["part15"])


if __name__ == "__main__":
    main()
