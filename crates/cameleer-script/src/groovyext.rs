//! Groovy AST transforms with runtime behavior beyond the generated methods of
//! [`crate::classes`]: `@Immutable` (read-only instances), `@Builder` (`Type.builder()...build()`),
//! `@Singleton` (`Type.instance`), `@Sortable` (`compareTo` by properties), `@AutoClone`
//! (`clone()`), `@Memoized` (methods cache their results per argument list).

use std::rc::{Rc, Weak};

use crate::ast::ClassDef;
use crate::interp::{Interp, R};
use crate::value::*;

fn has(def: &ClassDef, a: &str) -> bool {
    def.annotations.iter().any(|x| x == a)
}

fn class_def(it: &Interp, c: &Rc<Closure>) -> Option<std::sync::Arc<ClassDef>> {
    it.classes.get(&(Rc::as_ptr(c) as usize)).map(|i| i.def.clone())
}

/// Property names of a class (own and inherited, non-static fields).
fn prop_names(it: &Interp, c: &Rc<Closure>) -> Vec<String> {
    let mut chain = vec![];
    let mut cur = Some(c.clone());
    while let Some(k) = cur {
        chain.push(k.clone());
        cur = match &k.parent {
            Some(V::Func(p)) => Some(p.clone()),
            _ => None,
        };
    }
    chain.reverse();
    chain.iter().filter_map(|k| class_def(it, k)).flat_map(|d| d.fields.iter().filter(|f| !f.is_static).map(|f| f.name.clone()).collect::<Vec<_>>()).collect()
}

/// Install the Groovy globals of this module (`use`).
pub fn install(it: &mut Interp) {
    it.globals.define("use", V::Method(Rc::new((V::Null, "%groovy_use".to_string()))));
}

impl Interp {
    /// `use(Category, ...) { body }`: run the closure with the categories' static methods
    /// available as instance methods of their first parameter type.
    pub fn groovy_use(&mut self, args: &[V], pos: u32) -> R<V> {
        let Some((body, cats)) = args.split_last() else { return Ok(V::Null) };
        let n = self.categories.len();
        self.categories.extend(cats.iter().cloned());
        let r = self.call(body, V::Undef, vec![], pos);
        self.categories.truncate(n);
        r
    }

    /// A category method for `recv.name(args)` (innermost `use` first).
    pub fn category_call(&mut self, recv: &V, name: &str, args: &[V], pos: u32) -> R<Option<V>> {
        let cats: Vec<V> = self.categories.iter().rev().cloned().collect();
        for cat in cats {
            let V::Func(c) = &cat else { continue };
            let f = c.props.borrow().get(name).cloned();
            let Some(f) = f else { continue };
            let mut a = vec![recv.clone()];
            a.extend(args.iter().cloned());
            let applicable = match &f {
                V::Func(k) => match crate::overload::candidates(k) {
                    Some(cands) => self.select_overload(&cands, &a).is_some(),
                    None => k.def.params.first().is_some_and(|p| crate::overload::type_score(self, recv, p.ty.as_deref()).is_some()),
                },
                _ => false,
            };
            if applicable {
                return self.call(&f, V::Undef, a, pos).map(Some);
            }
        }
        Ok(None)
    }

    /// After a Groovy instance was constructed: freeze `@Immutable` instances.
    pub fn groovy_after_construct(&mut self, def: &ClassDef, this: &V) {
        if has(def, "Immutable") {
            if let V::Obj(o) = this {
                self.frozen.insert(Rc::as_ptr(o) as *const u8 as usize, Rc::downgrade(o));
            }
        }
    }

    /// Whether an object is a frozen (`@Immutable`) instance.
    pub fn is_frozen(&self, o: &ObjRef) -> bool {
        if self.frozen.is_empty() {
            return false;
        }
        let key = Rc::as_ptr(o) as *const u8 as usize;
        self.frozen.get(&key).and_then(Weak::upgrade).is_some_and(|x| Rc::ptr_eq(&x, o))
    }

    /// `ReadOnlyPropertyException` for a write to a frozen instance.
    pub fn frozen_error<X>(&self, o: &V, name: &str, pos: u32) -> R<X> {
        let cname = crate::classes::class_of(o).and_then(|c| c.def.name.clone()).unwrap_or_default();
        self.throw("ReadOnlyPropertyException", format!("Cannot set readonly property: {} for class: {}", name, cname), Some(pos))
    }

    /// Static calls generated by AST transforms (`Type.builder()`, `Type.getInstance()`).
    pub fn groovy_class_call(&mut self, c: &Rc<Closure>, name: &str, args: &[V], pos: u32) -> R<Option<V>> {
        let Some(def) = class_def(self, c) else { return Ok(None) };
        match name {
            "builder" if has(&def, "Builder") => {
                let mut p = PropMap::default();
                p.set("%builder", V::Func(c.clone()));
                p.set("%vals", V::new_obj());
                Ok(Some(V::obj(p)))
            }
            "getInstance" if has(&def, "Singleton") => self.groovy_singleton(c, pos).map(Some),
            _ => {
                let _ = args;
                Ok(None)
            }
        }
    }

    /// `Type.instance` of a `@Singleton` class.
    pub fn groovy_singleton(&mut self, c: &Rc<Closure>, pos: u32) -> R<V> {
        if let Some(v) = c.props.borrow().get("%instance") {
            return Ok(v.clone());
        }
        let v = self.construct_class(c, vec![], pos)?;
        c.props.borrow_mut().set("%instance", v.clone());
        Ok(v)
    }

    /// Static property reads generated by AST transforms (`Type.instance`).
    pub fn groovy_class_property(&mut self, c: &Rc<Closure>, name: &str, pos: u32) -> R<Option<V>> {
        if name == "instance" {
            if let Some(def) = class_def(self, c) {
                if has(&def, "Singleton") {
                    return self.groovy_singleton(c, pos).map(Some);
                }
            }
        }
        Ok(None)
    }

    /// Methods of a `@Builder` builder object: one setter per property and `build()`.
    pub fn groovy_builder_method(&mut self, o: &ObjRef, recv: &V, name: &str, args: &[V], pos: u32) -> R<Option<V>> {
        let (class, vals) = {
            let b = o.borrow();
            match (b.props.get("%builder"), b.props.get("%vals")) {
                (Some(c), Some(v)) => (c.clone(), v.clone()),
                _ => return Ok(None),
            }
        };
        if name == "build" {
            let V::Func(c) = &class else { return Ok(None) };
            let names = prop_names(self, c);
            let obj = self.construct_class(c, vec![], pos)?;
            if let V::Obj(vo) = &vals {
                let items: Vec<(Rc<str>, V)> = vo.borrow().props.iter().map(|(k, v)| (k.clone(), v.clone())).collect();
                for (k, v) in items {
                    if names.iter().any(|n| **n == *k) {
                        if let V::Obj(target) = &obj {
                            target.borrow_mut().props.set(&k, v);
                        }
                    }
                }
            }
            return Ok(Some(obj));
        }
        let V::Func(c) = &class else { return Ok(None) };
        if !prop_names(self, c).iter().any(|n| n == name) {
            return Ok(None);
        }
        if let V::Obj(vo) = &vals {
            vo.borrow_mut().props.set(name, args.first().cloned().unwrap_or(V::Null));
        }
        Ok(Some(recv.clone()))
    }

    /// Instance methods generated by AST transforms: `@Sortable` `compareTo`, `@AutoClone` `clone`.
    pub fn groovy_transform_method(&mut self, recv: &V, name: &str, args: &[V], pos: u32) -> R<Option<V>> {
        let Some(c) = crate::classes::class_of(recv) else { return Ok(None) };
        let Some(def) = class_def(self, &c) else { return Ok(None) };
        match name {
            "hashCode" if args.is_empty() && (has(&def, "EqualsAndHashCode") || has(&def, "Canonical") || has(&def, "Immutable")) => {
                let mut h: i64 = 17;
                for n in prop_names(self, &c) {
                    let v = self.get_member(recv, &n, pos)?;
                    let s = self.display(&v);
                    let vh = s.bytes().fold(0i64, |a, b| a.wrapping_mul(31).wrapping_add(b as i64)) as i32 as i64;
                    h = (h.wrapping_mul(31).wrapping_add(vh)) as i32 as i64;
                }
                Ok(Some(V::Int(h)))
            }
            "compareTo" if has(&def, "Sortable") => {
                let other = args.first().cloned().unwrap_or(V::Null);
                for n in prop_names(self, &c) {
                    let a = self.get_member(recv, &n, pos)?;
                    let b = self.get_member(&other, &n, pos)?;
                    match self.compare(&a, &b) {
                        Some(std::cmp::Ordering::Equal) | None => continue,
                        Some(o) => return Ok(Some(V::Int(o as i64))),
                    }
                }
                Ok(Some(V::Int(0)))
            }
            "clone" if has(&def, "AutoClone") => {
                let copy = self.construct_class(&c, vec![], pos)?;
                if let (V::Obj(src), V::Obj(dst)) = (recv, &copy) {
                    let items: Vec<(Rc<str>, V)> = src.borrow().props.iter().map(|(k, v)| (k.clone(), v.clone())).collect();
                    for (k, v) in items {
                        let v = match &v {
                            V::Arr(a) => V::arr(a.borrow().clone()),
                            other => other.clone(),
                        };
                        dst.borrow_mut().props.set(&k, v);
                    }
                }
                Ok(Some(copy))
            }
            _ => Ok(None),
        }
    }
}
