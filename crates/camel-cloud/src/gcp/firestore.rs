//! The `google-firestore` component (rust-camel; Camel has no Firestore component) over the
//! Cloud Firestore REST API (`projects/{p}/databases/{db}/documents`).
//!
//! `google-firestore://projectId[:collection]?serviceAccountKey=...&databaseId=(default)&operation=...`
//!
//! Documents are exchanged as plain maps: values are converted to and from Firestore typed
//! values (`stringValue`, `integerValue`, `doubleValue`, `booleanValue`, `nullValue`,
//! `bytesValue`, `arrayValue`, `mapValue`).
//!
//! Operations (`operation` / `CamelGoogleFirestoreOperation`, default `getDocument`); collection
//! from `CamelGoogleFirestoreCollection` or the uri (sub-collections as `a/doc/b`), document id
//! from `CamelGoogleFirestoreDocumentId`:
//! * `getDocument` (body = fields map), `listDocuments` (body = list of maps with `_id`).
//! * `createDocument` (body = map; id optional, generated by the service; sets the id header).
//! * `setDocument` (create or replace), `updateDocument` (merge of the body's top-level fields,
//!   the document must exist), `deleteDocument`.
//! * `runQuery`: body (or `CamelGoogleFirestoreQuery`) is either a `structuredQuery` object
//!   (passed through) or a map of field → value equality filters; options `orderBy`,
//!   `descending`, `limit` (headers `CamelGoogleFirestoreOrderBy`, `CamelGoogleFirestoreLimit`).
//!   Body = list of maps with `_id`.
//! Response header `CamelGoogleFirestoreUpdateTime`.

use std::collections::BTreeMap;
use std::sync::Arc;

use camel_core::error::{CamelError, Result};
use camel_core::message::Exchange;
use camel_core::value::Value;

use super::GcpConfig;
use crate::endpoint::{operation, unsupported, CloudService};
use crate::util::{base64_decode, base64_encode, header_i64, header_str, kinds, obj, uri_encode, Opts};

/// Header names.
pub mod headers {
    pub const OPERATION: &str = "CamelGoogleFirestoreOperation";
    pub const COLLECTION: &str = "CamelGoogleFirestoreCollection";
    pub const DOCUMENT_ID: &str = "CamelGoogleFirestoreDocumentId";
    pub const QUERY: &str = "CamelGoogleFirestoreQuery";
    pub const ORDER_BY: &str = "CamelGoogleFirestoreOrderBy";
    pub const LIMIT: &str = "CamelGoogleFirestoreLimit";
    pub const UPDATE_TIME: &str = "CamelGoogleFirestoreUpdateTime";
}

/// Convert a value to a Firestore typed value.
pub fn to_firestore(v: &Value) -> Value {
    match v {
        Value::Null => obj([("nullValue", Value::Null)]),
        Value::Bool(b) => obj([("booleanValue", Value::Bool(*b))]),
        Value::Int(i) => obj([("integerValue", Value::from(i.to_string()))]),
        Value::Float(f) => obj([("doubleValue", Value::Float(*f))]),
        Value::String(s) => obj([("stringValue", Value::from(s.clone()))]),
        Value::Bytes(b) => obj([("bytesValue", Value::from(base64_encode(b)))]),
        Value::Array(a) => obj([("arrayValue", obj([("values", Value::Array(a.iter().map(to_firestore).collect()))]))]),
        Value::Object(m) => obj([("mapValue", obj([("fields", fields_of(m))]))]),
    }
}

/// A map as Firestore `fields`.
pub fn fields_of(m: &BTreeMap<String, Value>) -> Value {
    Value::Object(m.iter().map(|(k, v)| (k.clone(), to_firestore(v))).collect())
}

/// Convert a Firestore typed value back to a value.
pub fn from_firestore(v: &Value) -> Value {
    let Some((k, x)) = v.as_object().and_then(|m| m.iter().next()) else { return Value::Null };
    match k.as_str() {
        "nullValue" => Value::Null,
        "booleanValue" => Value::Bool(x.is_truthy()),
        "integerValue" => x.as_i64().map(Value::Int).unwrap_or(Value::Null),
        "doubleValue" => x.as_f64().map(Value::Float).unwrap_or(Value::Null),
        "bytesValue" => Value::Bytes(base64_decode(&x.to_string()).unwrap_or_default()),
        "arrayValue" => Value::Array(x.get("values").and_then(|a| a.as_array()).map(|a| a.iter().map(from_firestore).collect()).unwrap_or_default()),
        "mapValue" => document_fields(x),
        _ => x.clone(),
    }
}

/// The `fields` of a document (or map value) as a plain map.
pub fn document_fields(doc: &Value) -> Value {
    Value::Object(doc.get("fields").and_then(|f| f.as_object()).map(|m| m.iter().map(|(k, v)| (k.clone(), from_firestore(v))).collect()).unwrap_or_default())
}

/// The Firestore endpoint configuration and client.
pub struct FirestoreService {
    pub gcp: GcpConfig,
    pub project: String,
    pub database: String,
    pub collection: Option<String>,
    pub operation: Option<String>,
    pub order_by: Option<String>,
    pub descending: bool,
    pub limit: Option<i64>,
}

/// Factory for the component.
pub fn create(remaining: &str, o: &mut Opts) -> Result<Arc<dyn CloudService>> {
    let gcp = GcpConfig::from_opts(o)?;
    let (project, collection) = match remaining.split_once(':') {
        Some((p, c)) => (p.to_string(), Some(c.to_string()).filter(|c| !c.is_empty())),
        None => (remaining.to_string(), None),
    };
    let project = Some(project).filter(|p| !p.is_empty()).or_else(|| gcp.project_id()).ok_or_else(|| CamelError::illegal_argument("Project id must be specified: google-firestore://projectId[:collection]"))?;
    Ok(Arc::new(FirestoreService {
        project,
        collection,
        database: o.string("databaseId", "(default)"),
        operation: o.get("operation"),
        order_by: o.get("orderBy"),
        descending: o.bool("descending", false)?,
        limit: crate::util::opt_i64(o, "limit")?,
        gcp,
    }))
}

fn with_id(doc: &Value) -> Value {
    let mut fields = document_fields(doc);
    if let (Value::Object(m), Some(name)) = (&mut fields, doc.get("name")) {
        m.insert("_id".into(), Value::from(name.to_string().rsplit('/').next().unwrap_or("").to_string()));
    }
    fields
}

fn encode_path(p: &str) -> String {
    p.split('/').map(|s| uri_encode(s, false)).collect::<Vec<_>>().join("/")
}

impl FirestoreService {
    fn root(&self) -> String {
        format!("{}/v1/projects/{}/databases/{}/documents", self.gcp.base("https://firestore.googleapis.com"), self.project, self.database)
    }

    fn collection(&self, ex: &Exchange) -> Result<String> {
        header_str(ex, headers::COLLECTION).or_else(|| self.collection.clone()).ok_or_else(|| CamelError::illegal_argument("Collection must be specified (uri or CamelGoogleFirestoreCollection)"))
    }

    fn doc_id(ex: &Exchange) -> Result<String> {
        header_str(ex, headers::DOCUMENT_ID).ok_or_else(|| CamelError::illegal_argument("Document id must be specified (CamelGoogleFirestoreDocumentId)"))
    }

    fn body_map(ex: &Exchange) -> Result<BTreeMap<String, Value>> {
        match ex.body() {
            Value::Object(m) => Ok(m.clone()),
            other => crate::util::parse_json(&other.to_bytes())?.as_object().cloned().ok_or_else(|| CamelError::illegal_argument("The document must be a map / JSON object")),
        }
    }

    fn call(&self, method: &str, url: &str, body: Option<&Value>) -> Result<Value> {
        self.gcp.json(method, url, body, kinds::FIRESTORE)
    }

    fn structured_query(&self, ex: &Exchange, collection: &str) -> Result<Value> {
        let q = ex.header(headers::QUERY).cloned().unwrap_or_else(|| ex.body().clone());
        let q = match q {
            Value::String(_) | Value::Bytes(_) => crate::util::parse_json(&q.to_bytes())?,
            other => other,
        };
        if let Some(sq) = q.get("structuredQuery") {
            return Ok(sq.clone());
        }
        if q.get("from").is_some() {
            return Ok(q);
        }
        let coll_id = collection.rsplit('/').next().unwrap_or(collection).to_string();
        let mut sq = BTreeMap::new();
        sq.insert("from".to_string(), Value::Array(vec![obj([("collectionId", Value::from(coll_id))])]));
        let filters: Vec<Value> = q
            .as_object()
            .map(|m| m.iter().map(|(k, v)| obj([("fieldFilter", obj([("field", obj([("fieldPath", Value::from(k.clone()))])), ("op", Value::from("EQUAL")), ("value", to_firestore(v))]))])).collect())
            .unwrap_or_default();
        match filters.len() {
            0 => {}
            1 => {
                sq.insert("where".into(), filters.into_iter().next().unwrap_or_default());
            }
            _ => {
                sq.insert("where".into(), obj([("compositeFilter", obj([("op", Value::from("AND")), ("filters", Value::Array(filters))]))]));
            }
        }
        if let Some(f) = header_str(ex, headers::ORDER_BY).or_else(|| self.order_by.clone()) {
            sq.insert("orderBy".into(), Value::Array(vec![obj([("field", obj([("fieldPath", Value::from(f))])), ("direction", Value::from(if self.descending { "DESCENDING" } else { "ASCENDING" }))])]));
        }
        if let Some(l) = header_i64(ex, headers::LIMIT).or(self.limit) {
            sq.insert("limit".into(), Value::Int(l));
        }
        Ok(Value::Object(sq))
    }
}

impl CloudService for FirestoreService {
    fn produce(&self, ex: &mut Exchange) -> Result<()> {
        let op = operation(ex, headers::OPERATION, &self.operation, "getDocument");
        match op.as_str() {
            "getDocument" => {
                let url = format!("{}/{}/{}", self.root(), encode_path(&self.collection(ex)?), uri_encode(&Self::doc_id(ex)?, false));
                let d = self.call("GET", &url, None)?;
                ex.set_header(headers::UPDATE_TIME, d.get("updateTime").cloned().unwrap_or_default());
                ex.set_body(document_fields(&d));
            }
            "listDocuments" => {
                let coll = encode_path(&self.collection(ex)?);
                let mut out = Vec::new();
                let mut token: Option<String> = None;
                loop {
                    let url = match &token {
                        Some(t) => format!("{}/{}?pageToken={}", self.root(), coll, uri_encode(t, false)),
                        None => format!("{}/{}", self.root(), coll),
                    };
                    let r = self.call("GET", &url, None)?;
                    out.extend(r.get("documents").and_then(|d| d.as_array()).cloned().unwrap_or_default().iter().map(with_id));
                    token = r.get("nextPageToken").map(|t| t.to_string()).filter(|t| !t.is_empty());
                    if token.is_none() {
                        break;
                    }
                }
                ex.set_body(Value::Array(out));
            }
            "createDocument" => {
                let coll = encode_path(&self.collection(ex)?);
                let url = match header_str(ex, headers::DOCUMENT_ID) {
                    Some(id) => format!("{}/{}?documentId={}", self.root(), coll, uri_encode(&id, false)),
                    None => format!("{}/{}", self.root(), coll),
                };
                let d = self.call("POST", &url, Some(&obj([("fields", fields_of(&Self::body_map(ex)?))])))?;
                let name = d.get("name").map(|n| n.to_string()).unwrap_or_default();
                ex.set_header(headers::DOCUMENT_ID, name.rsplit('/').next().unwrap_or("").to_string());
                ex.set_header(headers::UPDATE_TIME, d.get("updateTime").cloned().unwrap_or_default());
            }
            "setDocument" | "updateDocument" => {
                let map = Self::body_map(ex)?;
                let mut url = format!("{}/{}/{}", self.root(), encode_path(&self.collection(ex)?), uri_encode(&Self::doc_id(ex)?, false));
                if op == "updateDocument" {
                    let mask: Vec<String> = map.keys().map(|k| format!("updateMask.fieldPaths={}", uri_encode(k, false))).collect();
                    url = format!("{}?currentDocument.exists=true&{}", url, mask.join("&"));
                }
                let d = self.call("PATCH", &url, Some(&obj([("fields", fields_of(&map))])))?;
                ex.set_header(headers::UPDATE_TIME, d.get("updateTime").cloned().unwrap_or_default());
            }
            "deleteDocument" => {
                let url = format!("{}/{}/{}", self.root(), encode_path(&self.collection(ex)?), uri_encode(&Self::doc_id(ex)?, false));
                self.call("DELETE", &url, None)?;
            }
            "runQuery" => {
                let coll = self.collection(ex)?;
                let sq = self.structured_query(ex, &coll)?;
                // sub-collections: run the query under the parent document
                let parent = coll.rsplit_once('/').map(|(p, _)| format!("/{}", encode_path(p))).unwrap_or_default();
                let r = self.call("POST", &format!("{}{}:runQuery", self.root(), parent), Some(&obj([("structuredQuery", sq)])))?;
                let docs: Vec<Value> = r.as_array().cloned().unwrap_or_default().iter().filter_map(|e| e.get("document").map(with_id)).collect();
                ex.set_body(Value::Array(docs));
            }
            other => return Err(unsupported("google-firestore", other)),
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn typed_values_roundtrip() {
        let v = Value::object([
            ("s", Value::from("x")),
            ("i", Value::Int(5)),
            ("f", Value::Float(1.5)),
            ("b", Value::Bool(true)),
            ("n", Value::Null),
            ("a", Value::Array(vec![Value::Int(1), Value::from("two")])),
            ("m", Value::object([("k", "v")])),
            ("bytes", Value::Bytes(vec![1, 2])),
        ]);
        let fields = fields_of(v.as_object().unwrap());
        assert_eq!(fields.get("i").unwrap(), &obj([("integerValue", Value::from("5"))]));
        assert_eq!(document_fields(&obj([("fields", fields)])), v);
    }
}
