    #[test]
    fn korean_long_text_without_escapes_between_sets_i3() {
        let cs = CharacterSet::from_value("\\ISO 2022 IR 149");
        let b = b"\x1b$)CThe first line includes \xc7\xd1\xb1\xdb.\r\n\x1b$)CThe second line includes \xc7\xd1\xb1\xdb, too.\r\nThe third line";
        let text = "The first line includes 한글.\r\nThe second line includes 한글, too.\r\nThe third line";
        assert_eq!(cs.decode(b, Vr::LT), text);
        // the encoder designates G1 just before the first character that needs it
        let enc = cs.encode(text, Vr::LT).unwrap();
        assert_eq!(cs.decode(&enc, Vr::LT), text);
        assert!(enc.starts_with(b"The first line includes \x1b$)C\xc7\xd1"));
    }

