//! Specific Character Set (0008,0005) handling (PS3.5 section 6.1 and PS3.3 C.12.1.1.2).
//!
//! Supported defined terms:
//! - single-byte without code extensions: `ISO_IR 6` (default), `ISO_IR 100`, `101`, `109`,
//!   `110`, `144`, `127`, `126`, `138`, `148`, `203`, `13` (JIS X 0201), `166` (TIS 620);
//! - with code extensions (ISO/IEC 2022): `ISO 2022 IR 6`, `100`, `101`, `109`, `110`, `144`,
//!   `127`, `126`, `138`, `148`, `203`, `13`, `166`, and the multi-byte `ISO 2022 IR 87`
//!   (JIS X 0208), `ISO 2022 IR 159` (JIS X 0212), `ISO 2022 IR 149` (KS X 1001) and
//!   `ISO 2022 IR 58` (GB 2312);
//! - multi-byte without code extensions: `ISO_IR 192` (UTF-8), `GB18030` and `GBK`.
//!
//! The tables in `charset/*.bin` are generated by `scripts/gen-dicom-charsets.py` from
//! CPython's codecs (see `CHARSETS.md`).
//!
//! Decoding is lenient: unknown terms and bytes with no mapping in the active set decode as
//! Latin-1 (bytes 0x80-0xFF with no G1 set) or U+FFFD (unmapped codes of a designated set), and
//! never panic. Escape sequences are honoured wherever they appear. At a delimiter (`^`, `=`
//! and `\` in PN, `\` in the other multi-valued VRs, and every control character) G0 and G1
//! return to the sets of value 1, as PS3.5 6.1.2.5.3 requires; when value 1 designates no G1
//! set, the last designated G1 set stays (PS3.5 I.3 shows data that relies on it).
//!
//! Encoding emits escape sequences only where needed, picking the first term (in order)
//! whose sets can represent a character, switches G0 back to value 1's set explicitly before
//! every delimiter and at the end of the value, and treats G1 as reset at delimiters (so a
//! G1 set is designated again in each name component, as in PS3.5 Annex I and K).
//!
//! Multi-valued strings must be decoded as a whole and split afterwards: in GB 18030, GBK
//! and JIS X 0208 a byte 0x5C (`\`) can be the second byte of a character. Use
//! [`CharacterSet::decode_values`].

use std::collections::HashMap;
use std::sync::OnceLock;

use crate::vr::Vr;
use cameleer_core::error::{CamelError, Result};

static SB: &[u8] = include_bytes!("charset/sb.bin");
static JIS0208: &[u8] = include_bytes!("charset/jis0208.bin");
static JIS0212: &[u8] = include_bytes!("charset/jis0212.bin");
static KSX1001: &[u8] = include_bytes!("charset/ksx1001.bin");
static GB2312: &[u8] = include_bytes!("charset/gb2312.bin");
static GBK: &[u8] = include_bytes!("charset/gbk.bin");
static GB18030: &[u8] = include_bytes!("charset/gb18030.bin");
static GB18030R: &[u8] = include_bytes!("charset/gb18030r.bin");

/// ISO-IR numbers of the single-byte G1 tables in `sb.bin`, in file order.
const SB_IR: [u16; 11] = [100, 101, 109, 110, 144, 127, 126, 138, 148, 203, 166];
/// The final byte of the `ESC - F` (G1, 96-set) designation of each `SB_IR` table.
const SB_FINAL: [u8; 11] = [b'A', b'B', b'C', b'D', b'L', b'G', b'F', b'H', b'M', b'b', b'T'];

fn u16_at(t: &[u8], i: usize) -> u16 {
    u16::from_le_bytes([t[2 * i], t[2 * i + 1]])
}

fn u32_at(t: &[u8], i: usize) -> u32 {
    u32::from_le_bytes([t[4 * i], t[4 * i + 1], t[4 * i + 2], t[4 * i + 3]])
}

/// A graphic character set that can be designated to G0 or G1.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
enum Cs {
    /// ISO-IR 6 (ASCII), G0.
    Ascii,
    /// ISO-IR 14 (JIS X 0201 romaji), G0.
    Romaji,
    /// ISO-IR 13 (JIS X 0201 katakana), G1.
    Katakana,
    /// ISO-IR 13 designated to G0 by `ESC ( I` (decoding only).
    KatakanaG0,
    /// A single-byte 96-set from `sb.bin`, G1.
    Sb(u8),
    /// ISO-IR 87, G0.
    Jis0208,
    /// ISO-IR 159, G0.
    Jis0212,
    /// ISO-IR 149, G1.
    Ksx1001,
    /// ISO-IR 58, G1.
    Gb2312,
}

impl Cs {
    fn is_g0(self) -> bool {
        matches!(self, Cs::Ascii | Cs::Romaji | Cs::KatakanaG0 | Cs::Jis0208 | Cs::Jis0212)
    }

    fn escape(self) -> &'static [u8] {
        match self {
            Cs::Ascii => b"\x1b(B",
            Cs::Romaji => b"\x1b(J",
            Cs::Katakana => b"\x1b)I",
            Cs::KatakanaG0 => b"\x1b(I",
            Cs::Sb(i) => match SB_FINAL[i as usize] {
                b'A' => b"\x1b-A",
                b'B' => b"\x1b-B",
                b'C' => b"\x1b-C",
                b'D' => b"\x1b-D",
                b'L' => b"\x1b-L",
                b'G' => b"\x1b-G",
                b'F' => b"\x1b-F",
                b'H' => b"\x1b-H",
                b'M' => b"\x1b-M",
                b'b' => b"\x1b-b",
                _ => b"\x1b-T",
            },
            Cs::Jis0208 => b"\x1b$B",
            Cs::Jis0212 => b"\x1b$(D",
            Cs::Ksx1001 => b"\x1b$)C",
            Cs::Gb2312 => b"\x1b$)A",
        }
    }

    fn table94(self) -> Option<&'static [u8]> {
        match self {
            Cs::Jis0208 => Some(JIS0208),
            Cs::Jis0212 => Some(JIS0212),
            Cs::Ksx1001 => Some(KSX1001),
            Cs::Gb2312 => Some(GB2312),
            _ => None,
        }
    }

    fn name(self) -> String {
        match self {
            Cs::Ascii => "ISO-IR 6".into(),
            Cs::Romaji => "ISO-IR 14".into(),
            Cs::Katakana | Cs::KatakanaG0 => "ISO-IR 13".into(),
            Cs::Sb(i) => format!("ISO-IR {}", SB_IR[i as usize]),
            Cs::Jis0208 => "ISO-IR 87".into(),
            Cs::Jis0212 => "ISO-IR 159".into(),
            Cs::Ksx1001 => "ISO-IR 149".into(),
            Cs::Gb2312 => "ISO-IR 58".into(),
        }
    }

    /// Encode one character in this set (`None` if it has no code here).
    fn encode(self, c: char, out: &mut Vec<u8>) -> bool {
        let u = c as u32;
        match self {
            Cs::Ascii => {
                if u < 0x80 {
                    out.push(u as u8);
                    return true;
                }
            }
            Cs::Romaji => {
                if u < 0x80 && c != '\\' && c != '~' {
                    out.push(u as u8);
                    return true;
                }
                if c == '\u{a5}' {
                    out.push(0x5C);
                    return true;
                }
                if c == '\u{203e}' {
                    out.push(0x7E);
                    return true;
                }
            }
            Cs::Katakana => {
                if (0xFF61..=0xFF9F).contains(&u) {
                    out.push((u - 0xFF61) as u8 + 0xA1);
                    return true;
                }
            }
            Cs::KatakanaG0 => {}
            Cs::Sb(i) => {
                if let Some(&b) = sb_reverse(i).get(&u) {
                    out.push(b);
                    return true;
                }
            }
            Cs::Jis0208 | Cs::Jis0212 | Cs::Ksx1001 | Cs::Gb2312 => {
                if let Some(&code) = reverse94(self).get(&u) {
                    let (r, c) = ((code >> 8) as u8, code as u8);
                    if self.is_g0() {
                        out.extend_from_slice(&[r, c]);
                    } else {
                        out.extend_from_slice(&[r | 0x80, c | 0x80]);
                    }
                    return true;
                }
            }
        }
        false
    }
}

fn sb_reverse(i: u8) -> &'static HashMap<u32, u8> {
    static MAPS: OnceLock<Vec<HashMap<u32, u8>>> = OnceLock::new();
    &MAPS.get_or_init(|| {
        (0..SB_IR.len())
            .map(|t| {
                let mut m = HashMap::new();
                for k in 0..96 {
                    let c = u16_at(SB, t * 96 + k);
                    if c != 0 {
                        m.entry(c as u32).or_insert(0xA0 + k as u8);
                    }
                }
                m
            })
            .collect()
    })[i as usize]
}

fn build94(t: &[u8]) -> HashMap<u32, u16> {
    let mut m = HashMap::new();
    for r in 0..94 {
        for c in 0..94 {
            let u = u16_at(t, r * 94 + c);
            if u != 0 {
                m.entry(u as u32).or_insert((((r + 0x21) << 8) | (c + 0x21)) as u16);
            }
        }
    }
    m
}

fn reverse94(cs: Cs) -> &'static HashMap<u32, u16> {
    static J8: OnceLock<HashMap<u32, u16>> = OnceLock::new();
    static J12: OnceLock<HashMap<u32, u16>> = OnceLock::new();
    static K: OnceLock<HashMap<u32, u16>> = OnceLock::new();
    static G: OnceLock<HashMap<u32, u16>> = OnceLock::new();
    match cs {
        Cs::Jis0208 => J8.get_or_init(|| build94(JIS0208)),
        Cs::Jis0212 => J12.get_or_init(|| build94(JIS0212)),
        Cs::Ksx1001 => K.get_or_init(|| build94(KSX1001)),
        _ => G.get_or_init(|| build94(GB2312)),
    }
}

/// A two-byte GBK / GB 18030 table: (lead 0x81..0xFE) x (trail 0x40..0xFE).
fn table2_get(t: &[u8], lead: u8, trail: u8) -> u16 {
    if !(0x81..=0xFE).contains(&lead) || !(0x40..=0xFE).contains(&trail) || trail == 0x7F {
        return 0;
    }
    u16_at(t, (lead - 0x81) as usize * 191 + (trail - 0x40) as usize)
}

fn reverse2(gbk: bool) -> &'static HashMap<u32, u16> {
    static A: OnceLock<HashMap<u32, u16>> = OnceLock::new();
    static B: OnceLock<HashMap<u32, u16>> = OnceLock::new();
    let build = |t: &[u8]| {
        let mut m = HashMap::new();
        for lead in 0..126usize {
            for trail in 0..191usize {
                let u = u16_at(t, lead * 191 + trail);
                if u != 0 {
                    m.entry(u as u32).or_insert((((lead + 0x81) << 8) | (trail + 0x40)) as u16);
                }
            }
        }
        m
    };
    if gbk {
        A.get_or_init(|| build(GBK))
    } else {
        B.get_or_init(|| build(GB18030))
    }
}

/// The four-byte BMP runs of GB 18030: (linear, code point, length).
fn gb18030_runs() -> impl Iterator<Item = (u32, u32, u32)> {
    (0..GB18030R.len() / 12).map(|i| (u32_at(GB18030R, 3 * i), u32_at(GB18030R, 3 * i + 1), u32_at(GB18030R, 3 * i + 2)))
}

/// What a defined term stands for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Term {
    /// Sets of a single-byte or ISO 2022 term (G0, G1).
    Sets(Option<Cs>, Option<Cs>),
    Utf8,
    Gb18030,
    Gbk,
    Unknown,
}

fn parse_term(t: &str) -> Term {
    let t = t.trim();
    match t {
        "" => return Term::Sets(Some(Cs::Ascii), None),
        "ISO_IR 192" => return Term::Utf8,
        "GB18030" => return Term::Gb18030,
        "GBK" => return Term::Gbk,
        _ => {}
    }
    let num = t.strip_prefix("ISO 2022 IR ").or_else(|| t.strip_prefix("ISO_IR ")).or_else(|| t.strip_prefix("ISO-IR "));
    let Some(n) = num.and_then(|n| n.trim().parse::<u16>().ok()) else {
        return Term::Unknown;
    };
    match n {
        6 => Term::Sets(Some(Cs::Ascii), None),
        13 => Term::Sets(Some(Cs::Romaji), Some(Cs::Katakana)),
        87 => Term::Sets(Some(Cs::Jis0208), None),
        159 => Term::Sets(Some(Cs::Jis0212), None),
        149 => Term::Sets(None, Some(Cs::Ksx1001)),
        58 => Term::Sets(None, Some(Cs::Gb2312)),
        n => match SB_IR.iter().position(|&x| x == n) {
            Some(i) => Term::Sets(Some(Cs::Ascii), Some(Cs::Sb(i as u8))),
            None => Term::Unknown,
        },
    }
}

/// The character repertoires named by Specific Character Set.
#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct CharacterSet {
    /// The defined terms, in order (`["ISO 2022 IR 6", "ISO 2022 IR 87"]`); empty for the
    /// default repertoire (ISO-IR 6, ASCII).
    pub terms: Vec<String>,
}

/// The decoding / encoding mode of a whole character set.
enum Mode {
    Iso2022 { g0: Cs, g1: Option<Cs>, cands: Vec<Cs> },
    Utf8,
    Gb18030,
    Gbk,
}

impl CharacterSet {
    /// The default repertoire.
    pub fn default_repertoire() -> CharacterSet {
        CharacterSet::default()
    }

    /// Parse the value of (0008,0005) (backslash separated, values trimmed).
    pub fn from_value(value: &str) -> CharacterSet {
        CharacterSet { terms: value.split('\\').map(|s| s.trim().to_string()).collect() }
    }

    /// Whether this is UTF-8 (`ISO_IR 192`) or the default repertoire.
    pub fn is_utf8_compatible(&self) -> bool {
        self.terms.iter().all(|t| t.is_empty() || t == "ISO_IR 192" || t == "ISO_IR 6" || t == "ISO 2022 IR 6")
    }

    /// Whether every term is one this module knows.
    pub fn is_supported(&self) -> bool {
        self.terms.iter().all(|t| parse_term(t) != Term::Unknown)
    }

    fn mode(&self) -> Mode {
        let terms: Vec<Term> = self.terms.iter().map(|t| parse_term(t)).collect();
        for t in &terms {
            match t {
                Term::Utf8 => return Mode::Utf8,
                Term::Gb18030 => return Mode::Gb18030,
                Term::Gbk => return Mode::Gbk,
                _ => {}
            }
        }
        let (mut g0, mut g1) = (Cs::Ascii, None);
        if let Some(Term::Sets(a, b)) = terms.first() {
            if let Some(a) = a {
                if matches!(a, Cs::Ascii | Cs::Romaji) {
                    g0 = *a;
                }
            }
            g1 = *b;
        }
        let mut cands = Vec::new();
        if terms.is_empty() || !matches!(terms[0], Term::Sets(Some(_), _)) {
            cands.push(Cs::Ascii);
        }
        for t in &terms {
            if let Term::Sets(a, b) = t {
                for cs in [a, b].into_iter().flatten() {
                    if !cands.contains(cs) {
                        cands.push(*cs);
                    }
                }
            }
        }
        Mode::Iso2022 { g0, g1, cands }
    }

    /// Decode a string value of the given VR to Unicode.
    pub fn decode(&self, bytes: &[u8], vr: Vr) -> String {
        if !vr.uses_charset() {
            return bytes.iter().map(|&b| b as char).collect();
        }
        match self.mode() {
            Mode::Utf8 => String::from_utf8_lossy(bytes).into_owned(),
            Mode::Gb18030 => decode_gb(bytes, false),
            Mode::Gbk => decode_gb(bytes, true),
            Mode::Iso2022 { g0, g1, .. } => decode_2022(bytes, vr, g0, g1),
        }
    }

    /// Decode a (possibly multi-valued) string value and split it into its values.
    pub fn decode_values(&self, bytes: &[u8], vr: Vr) -> Vec<String> {
        let s = self.decode(bytes, vr);
        if vr.is_multi_valued_string() {
            s.split('\\').map(str::to_string).collect()
        } else {
            vec![s]
        }
    }

    /// Encode a Unicode string value of the given VR to bytes in this character set.
    pub fn encode(&self, s: &str, vr: Vr) -> Result<Vec<u8>> {
        if !vr.uses_charset() {
            return s
                .chars()
                .map(|c| {
                    u8::try_from(c as u32).map_err(|_| CamelError::illegal_argument(format!("character {c:?} is not allowed in a {vr} value")))
                })
                .collect();
        }
        match self.mode() {
            Mode::Utf8 => Ok(s.as_bytes().to_vec()),
            Mode::Gb18030 => encode_gb(s, false),
            Mode::Gbk => encode_gb(s, true),
            Mode::Iso2022 { g0, g1, cands } => encode_2022(s, vr, g0, g1, &cands, &self.terms),
        }
    }
}

/// Whether the ASCII byte is a delimiter that returns to the initial sets.
fn is_delim(b: u8, vr: Vr) -> bool {
    if b < 0x20 && b != 0x1B {
        return true;
    }
    match b {
        b'\\' => vr.is_multi_valued_string(),
        b'^' | b'=' => vr == Vr::PN,
        _ => false,
    }
}

/// Parse an escape sequence at `b[0] == ESC`: (bytes consumed, set designated).
fn parse_escape(b: &[u8]) -> Option<(usize, Cs)> {
    let r = &b[1..];
    let two = |s: &[u8]| r.starts_with(s);
    let found = if two(b"(B") {
        (3, Cs::Ascii)
    } else if two(b"(J") {
        (3, Cs::Romaji)
    } else if two(b"(I") {
        (3, Cs::KatakanaG0)
    } else if two(b")I") {
        (3, Cs::Katakana)
    } else if two(b"$B") || two(b"$@") {
        (3, Cs::Jis0208)
    } else if two(b"$(D") {
        (4, Cs::Jis0212)
    } else if two(b"$)C") {
        (4, Cs::Ksx1001)
    } else if two(b"$)A") {
        (4, Cs::Gb2312)
    } else if r.len() >= 2 && r[0] == b'-' {
        let i = SB_FINAL.iter().position(|&f| f == r[1])?;
        (3, Cs::Sb(i as u8))
    } else {
        return None;
    };
    Some(found)
}

fn decode_2022(bytes: &[u8], vr: Vr, init_g0: Cs, init_g1: Option<Cs>) -> String {
    let mut out = String::with_capacity(bytes.len());
    let (mut g0, mut g1) = (init_g0, init_g1);
    let mut i = 0;
    let reset = |g0: &mut Cs, g1: &mut Option<Cs>| {
        *g0 = init_g0;
        if init_g1.is_some() {
            *g1 = init_g1;
        }
    };
    while i < bytes.len() {
        let b = bytes[i];
        if b == 0x1B {
            if let Some((n, cs)) = parse_escape(&bytes[i..]) {
                if cs.is_g0() {
                    g0 = cs;
                } else {
                    g1 = Some(cs);
                }
                i += n;
                continue;
            }
            out.push('\u{1b}');
            i += 1;
            continue;
        }
        if b < 0x80 {
            if b < 0x20 {
                out.push(b as char);
                reset(&mut g0, &mut g1);
                i += 1;
                continue;
            }
            if let Some(t) = g0.table94() {
                if b == 0x20 || b == 0x7F || i + 1 >= bytes.len() || !(0x21..0x7F).contains(&bytes[i + 1]) {
                    out.push(b as char);
                    i += 1;
                    continue;
                }
                let u = u16_at(t, (b - 0x21) as usize * 94 + (bytes[i + 1] - 0x21) as usize);
                out.push(char::from_u32(u as u32).filter(|_| u != 0).unwrap_or('\u{fffd}'));
                i += 2;
                continue;
            }
            let c = match g0 {
                Cs::Romaji if b == 0x5C => {
                    if vr.is_multi_valued_string() {
                        '\\'
                    } else {
                        '\u{a5}'
                    }
                }
                Cs::Romaji if b == 0x7E => '\u{203e}',
                Cs::KatakanaG0 if (0x21..=0x5F).contains(&b) => char::from_u32(0xFF61 + (b - 0x21) as u32).unwrap_or('\u{fffd}'),
                _ => b as char,
            };
            out.push(c);
            if is_delim(b, vr) {
                reset(&mut g0, &mut g1);
            }
            i += 1;
            continue;
        }
        match g1 {
            Some(cs @ (Cs::Ksx1001 | Cs::Gb2312)) if b >= 0xA1 && i + 1 < bytes.len() && bytes[i + 1] >= 0xA1 && bytes[i + 1] < 0xFF && b < 0xFF => {
                let t = cs.table94().unwrap_or(GB2312);
                let u = u16_at(t, (b - 0xA1) as usize * 94 + (bytes[i + 1] - 0xA1) as usize);
                out.push(char::from_u32(u as u32).filter(|_| u != 0).unwrap_or('\u{fffd}'));
                i += 2;
                continue;
            }
            Some(Cs::Sb(t)) if b >= 0xA0 => {
                let u = u16_at(SB, t as usize * 96 + (b - 0xA0) as usize);
                out.push(char::from_u32(u as u32).filter(|_| u != 0).unwrap_or('\u{fffd}'));
            }
            Some(Cs::Katakana) if (0xA1..=0xDF).contains(&b) => out.push(char::from_u32(0xFF61 + (b - 0xA1) as u32).unwrap_or('\u{fffd}')),
            Some(_) if b >= 0xA0 => out.push('\u{fffd}'),
            // C1 controls, or no G1 set: Latin-1, lossless
            _ => out.push(b as char),
        }
        i += 1;
    }
    out
}

fn encode_2022(s: &str, vr: Vr, init_g0: Cs, init_g1: Option<Cs>, cands: &[Cs], terms: &[String]) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(s.len());
    let (mut g0, mut g1) = (init_g0, init_g1);
    let has_g1 = cands.iter().any(|c| !c.is_g0());
    'chars: for c in s.chars() {
        let u = c as u32;
        if u < 0x80 && is_delim(u as u8, vr) {
            if g0 != init_g0 {
                out.extend_from_slice(init_g0.escape());
                g0 = init_g0;
            }
            out.push(u as u8);
            g1 = init_g1;
            continue;
        }
        if g0.encode(c, &mut out) {
            continue;
        }
        if let Some(cs) = g1 {
            if cs.encode(c, &mut out) {
                continue;
            }
        }
        for &cs in cands {
            let mut buf = Vec::new();
            if cs.encode(c, &mut buf) {
                out.extend_from_slice(cs.escape());
                if cs.is_g0() {
                    g0 = cs;
                } else {
                    g1 = Some(cs);
                }
                out.extend_from_slice(&buf);
                continue 'chars;
            }
        }
        // the default repertoire without a G1 set decodes 0x80-0xFF as Latin-1; encode the same
        if !has_g1 && (0x80..=0xFF).contains(&u) {
            out.push(u as u8);
            continue;
        }
        // romaji has no backslash or tilde; keep the byte rather than fail
        if g0 == Cs::Romaji && (c == '\\' || c == '~') {
            out.push(u as u8);
            continue;
        }
        let names: Vec<String> = cands.iter().map(|c| c.name()).collect();
        return Err(CamelError::illegal_argument(format!(
            "character {c:?} (U+{u:04X}) cannot be encoded in Specific Character Set {:?} ({})",
            terms.join("\\"),
            names.join(", ")
        )));
    }
    if g0 != init_g0 {
        out.extend_from_slice(init_g0.escape());
    }
    Ok(out)
}

fn decode_gb(bytes: &[u8], gbk: bool) -> String {
    let t = if gbk { GBK } else { GB18030 };
    let mut out = String::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b < 0x80 {
            out.push(b as char);
            i += 1;
            continue;
        }
        if (0x81..=0xFE).contains(&b) && i + 1 < bytes.len() {
            let b2 = bytes[i + 1];
            if !gbk && (0x30..=0x39).contains(&b2) && i + 3 < bytes.len() && (0x81..=0xFE).contains(&bytes[i + 2]) && (0x30..=0x39).contains(&bytes[i + 3]) {
                let lin = (((b - 0x81) as u32 * 10 + (b2 - 0x30) as u32) * 126 + (bytes[i + 2] - 0x81) as u32) * 10 + (bytes[i + 3] - 0x30) as u32;
                out.push(gb18030_four(lin).unwrap_or('\u{fffd}'));
                i += 4;
                continue;
            }
            let u = table2_get(t, b, b2);
            if u != 0 {
                out.push(char::from_u32(u as u32).unwrap_or('\u{fffd}'));
                i += 2;
                continue;
            }
        }
        out.push('\u{fffd}');
        i += 1;
    }
    out
}

/// The character of a four-byte GB 18030 sequence by its linear index.
fn gb18030_four(lin: u32) -> Option<char> {
    // supplementary planes start at 0x90308130
    const SUPP: u32 = (0x90 - 0x81) * 12600;
    if lin >= SUPP {
        return char::from_u32(0x10000 + (lin - SUPP)).filter(|&c| (c as u32) <= 0x10FFFF);
    }
    gb18030_runs().find(|&(l, _, n)| lin >= l && lin < l + n).and_then(|(l, c, _)| char::from_u32(c + (lin - l)))
}

fn encode_gb(s: &str, gbk: bool) -> Result<Vec<u8>> {
    let rev = reverse2(gbk);
    let mut out = Vec::with_capacity(s.len());
    for c in s.chars() {
        let u = c as u32;
        if u < 0x80 {
            out.push(u as u8);
            continue;
        }
        if let Some(&code) = rev.get(&u) {
            out.extend_from_slice(&code.to_be_bytes());
            continue;
        }
        if !gbk {
            let lin = if u >= 0x10000 {
                Some((0x90 - 0x81) * 12600 + (u - 0x10000))
            } else {
                gb18030_runs().find(|&(_, cp, n)| u >= cp && u < cp + n).map(|(l, cp, _)| l + (u - cp))
            };
            if let Some(lin) = lin {
                let (b1, r) = (lin / 12600, lin % 12600);
                let (b2, r) = (r / 1260, r % 1260);
                let (b3, b4) = (r / 10, r % 10);
                out.extend_from_slice(&[0x81 + b1 as u8, 0x30 + b2 as u8, 0x81 + b3 as u8, 0x30 + b4 as u8]);
                continue;
            }
        }
        return Err(CamelError::illegal_argument(format!(
            "character {c:?} (U+{u:04X}) cannot be encoded in Specific Character Set {}",
            if gbk { "GBK" } else { "GB18030" }
        )));
    }
    Ok(out)
}

