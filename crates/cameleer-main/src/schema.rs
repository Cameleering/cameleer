//! `cameleer schema`: a JSON Schema (draft 2020-12) of the Camel YAML DSL, generated from the
//! loader's DSL model ([`cameleer_yaml::model`]), the same tables `cameleer validate` uses.
//!
//! Editors use it with a modeline: `# yaml-language-server: $schema=./camel-yaml-dsl.json`.
//!
//! Covered: the top-level elements, every step with its keys (required keys, booleans,
//! integers and durations, which also accept `{{placeholders}}`), nested elements (`when`,
//! `doCatch`, error handlers, redelivery policies, REST verbs, ...), expressions in every
//! language form, endpoint URIs with `parameters`. Not covered: the options of each component's
//! URI, of each data format and of each language (checked by `cameleer validate`, which
//! resolves endpoints and compiles expressions), and the Kamelet / Pipe / Integration
//! resource formats.

use cameleer_yaml::model::{self, Expr, Key, Kind, Model, Shorthand};

/// The schema as a JSON string.
pub fn json_schema() -> String {
    let mut defs: Vec<(String, String)> = Vec::new();
    // shared definitions
    let langs = model::languages();
    defs.push(("scalar".into(), r#"{"type":["string","number","boolean"]}"#.into()));
    defs.push((
        "languageValue".into(),
        r#"{"anyOf":[{"type":["string","number","boolean","null"]},{"type":"object","properties":{"expression":{"type":["string","number","boolean"]}}}]}"#.into(),
    ));
    let lang_props: Vec<String> = langs.iter().map(|l| format!("{}:{{\"$ref\":\"#/$defs/languageValue\"}}", q(l))).collect();
    defs.push((
        "expressionObject".into(),
        format!(
            "{{\"type\":\"object\",\"description\":\"An expression: one language key (simple, constant, jsonpath, ...)\",\"properties\":{{{},\"expression\":{{\"$ref\":\"#/$defs/expression\"}}}},\"minProperties\":1,\"maxProperties\":1,\"additionalProperties\":false}}",
            lang_props.join(",")
        ),
    ));
    defs.push((
        "expression".into(),
        r##"{"anyOf":[{"type":["string","number","boolean"]},{"$ref":"#/$defs/expressionObject"}]}"##.into(),
    ));
    defs.push((
        "endpoint".into(),
        r#"{"anyOf":[{"type":"string","description":"An endpoint URI (scheme:path?options)"},{"type":"object","properties":{"uri":{"type":"string"},"parameters":{"type":"object"}},"required":["uri"]}]}"#.into(),
    ));
    let step_props: Vec<String> = model::STEPS.iter().map(|m| format!("{}:{{\"$ref\":\"#/$defs/{}\"}}", q(m.name), step_def(m.name))).collect();
    let step_names: Vec<String> = model::STEPS.iter().map(|m| q(m.name)).collect();
    defs.push((
        "step".into(),
        format!(
            "{{\"anyOf\":[{{\"type\":\"object\",\"properties\":{{{}}},\"minProperties\":1,\"maxProperties\":1,\"additionalProperties\":false}},{{\"enum\":[{}]}}]}}",
            step_props.join(","),
            step_names.join(",")
        ),
    ));
    defs.push(("steps".into(), r##"{"type":"array","items":{"$ref":"#/$defs/step"}}"##.into()));
    for m in model::STEPS {
        defs.push((step_def(m.name), model_schema(m)));
    }
    for m in model::MODELS {
        defs.push((m.name.to_string(), model_schema(m)));
    }
    let top_props: Vec<String> = model::TOP_LEVEL.iter().map(|k| format!("{}:{}", q(k.name), kind_schema(k.kind))).collect();
    defs.push((
        "topLevel".into(),
        format!(
            "{{\"anyOf\":[{{\"type\":\"object\",\"properties\":{{{}}},\"minProperties\":1,\"maxProperties\":1,\"additionalProperties\":false}},{{\"$ref\":\"#/$defs/route\"}}]}}",
            top_props.join(",")
        ),
    ));
    let mut out = String::new();
    out.push_str("{\"$schema\":\"https://json-schema.org/draft/2020-12/schema\",");
    out.push_str("\"$id\":\"https://cameleer.dev/schema/camel-yaml-dsl.json\",");
    out.push_str("\"title\":\"Camel YAML DSL (Cameleer)\",");
    out.push_str(&format!(
        "\"description\":{},",
        q(&format!("Generated by cameleer schema {} from the YAML DSL loader's model. Endpoint, data format and language options are not described: use `cameleer validate` to check them.", env!("CARGO_PKG_VERSION")))
    ));
    out.push_str("\"type\":\"array\",\"items\":{\"$ref\":\"#/$defs/topLevel\"},\"$defs\":{");
    for (i, (name, s)) in defs.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        out.push_str(&format!("\n{}:{}", q(name), s));
    }
    out.push_str("\n}}\n");
    out
}

fn step_def(name: &str) -> String {
    format!("step.{}", name)
}

/// The `$defs` name of a model referenced by a key (nested mappings first, like
/// [`model::model`]).
fn def_name(name: &str) -> String {
    if model::MODELS.iter().any(|m| m.name == name) {
        name.to_string()
    } else {
        step_def(name)
    }
}

fn q(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn kind_schema(k: Kind) -> String {
    match k {
        Kind::Any => "{}".into(),
        Kind::Scalar => r##"{"$ref":"#/$defs/scalar"}"##.into(),
        Kind::Bool => r#"{"type":["boolean","string"]}"#.into(),
        Kind::Int => r#"{"type":["integer","string"]}"#.into(),
        Kind::Number => r#"{"type":["number","string"]}"#.into(),
        Kind::Duration => r#"{"type":["integer","string"],"description":"milliseconds, or a duration such as 5s"}"#.into(),
        Kind::StringList => r#"{"anyOf":[{"type":"string"},{"type":"array","items":{"type":["string","number"]}}]}"#.into(),
        Kind::Map | Kind::Parameters => r#"{"type":"object"}"#.into(),
        Kind::Steps => r##"{"$ref":"#/$defs/steps"}"##.into(),
        Kind::Expression => r##"{"$ref":"#/$defs/expression"}"##.into(),
        Kind::Predicate => r##"{"anyOf":[{"type":"boolean"},{"$ref":"#/$defs/expression"}]}"##.into(),
        Kind::Endpoint => r##"{"$ref":"#/$defs/endpoint"}"##.into(),
        Kind::Uri => r#"{"type":"string"}"#.into(),
        Kind::Object(n) => format!("{{\"$ref\":\"#/$defs/{}\"}}", def_name(n)),
        Kind::List(n) => {
            let r = format!("{{\"$ref\":\"#/$defs/{}\"}}", def_name(n));
            format!(
                "{{\"anyOf\":[{{\"type\":\"array\",\"items\":{{\"anyOf\":[{r},{{\"type\":\"object\",\"properties\":{{{n}:{r}}},\"required\":[{n}],\"additionalProperties\":false}}]}}}},{r}]}}",
                r = r,
                n = q(n)
            )
        }
        Kind::Section(n) => format!("{{\"anyOf\":[{{\"$ref\":\"#/$defs/steps\"}},{{\"$ref\":\"#/$defs/{}\"}}]}}", def_name(n)),
    }
}

fn model_schema(m: &Model) -> String {
    let mut props: Vec<String> = Vec::new();
    let mut keys: Vec<Key> = m.keys.to_vec();
    if m.step {
        keys.extend(model::COMMON_STEP_KEYS.iter().copied());
    }
    for k in &keys {
        props.push(format!("{}:{}", q(k.name), kind_schema(k.kind)));
    }
    if m.expression != Expr::No {
        for l in model::languages() {
            if !keys.iter().any(|k| k.name == l) {
                props.push(format!("{}:{{\"$ref\":\"#/$defs/languageValue\"}}", q(l)));
            }
        }
        if !keys.iter().any(|k| k.name == "expression") {
            props.push("\"expression\":{\"$ref\":\"#/$defs/expression\"}".into());
        }
    }
    let mut obj = format!("{{\"type\":\"object\",\"description\":{},\"properties\":{{{}}}", q(m.doc), props.join(","));
    // required keys (sets of alternatives) and the expression
    let mut all_of: Vec<String> = Vec::new();
    let single: Vec<String> = m.required.iter().filter(|a| a.len() == 1).map(|a| q(a[0])).collect();
    if !single.is_empty() {
        obj.push_str(&format!(",\"required\":[{}]", single.join(",")));
    }
    for alts in m.required.iter().filter(|a| a.len() > 1) {
        let any: Vec<String> = alts.iter().map(|a| format!("{{\"required\":[{}]}}", q(a))).collect();
        all_of.push(format!("{{\"anyOf\":[{}]}}", any.join(",")));
    }
    if m.expression == Expr::Required {
        let mut names: Vec<&str> = model::languages();
        names.push("expression");
        names.extend(m.expression_alternatives.iter().copied());
        let any: Vec<String> = names.iter().map(|a| format!("{{\"required\":[{}]}}", q(a))).collect();
        all_of.push(format!("{{\"anyOf\":[{}]}}", any.join(",")));
    }
    if !all_of.is_empty() {
        obj.push_str(&format!(",\"allOf\":[{}]", all_of.join(",")));
    }
    if m.one_of {
        obj.push_str(",\"minProperties\":1");
    }
    if m.one_extra {
        obj.push_str(",\"additionalProperties\":{\"anyOf\":[{\"type\":\"object\"},{\"type\":\"string\"},{\"type\":\"null\"}]},\"minProperties\":1");
    } else if m.open {
        obj.push_str(",\"additionalProperties\":true");
    } else {
        obj.push_str(",\"additionalProperties\":false");
    }
    obj.push('}');
    match m.shorthand {
        Shorthand::No => obj,
        Shorthand::Uri | Shorthand::Text => format!("{{\"anyOf\":[{{\"type\":[\"string\",\"number\",\"boolean\"]}},{}]}}", obj),
        Shorthand::Expression => format!("{{\"anyOf\":[{{\"type\":[\"string\",\"number\",\"boolean\"]}},{}]}}", obj),
    }
}
