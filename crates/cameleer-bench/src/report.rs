//! `cameleer-bench report`: turn the records collected by `scripts/bench.sh` into
//! `docs/BENCHMARKS.md`.

use std::collections::BTreeMap;

/// The owner's target: Cameleer at least this many times better than Apache Camel.
pub const TARGET: f64 = 4.0;

/// One parsed record line: kind plus key=value fields.
#[derive(Clone, Debug, Default)]
pub struct Record {
    pub kind: String,
    pub fields: BTreeMap<String, String>,
}

impl Record {
    pub fn parse(line: &str) -> Option<Record> {
        let mut parts = line.split_whitespace();
        let kind = parts.next()?.to_string();
        if !matches!(kind.as_str(), "RESULT" | "RSS" | "STARTUP" | "VERSION") {
            return None;
        }
        let fields = parts.filter_map(|p| p.split_once('=')).map(|(k, v)| (k.to_string(), v.to_string())).collect();
        Some(Record { kind, fields })
    }

    pub fn get(&self, k: &str) -> Option<&str> {
        self.fields.get(k).map(|s| s.as_str())
    }

    pub fn num(&self, k: &str) -> Option<f64> {
        self.get(k).and_then(|v| v.parse().ok())
    }
}

/// Human description of each scenario, in report order.
pub const DESCRIPTIONS: &[(&str, &str)] = &[
    ("direct", "`direct:` → processor (set header) → counting sink; 1 caller thread"),
    ("seda", "`seda:` (size 1000, blockWhenFull) with 4 concurrent consumers; 4 InOnly producer threads; throughput counted at the consumer"),
    ("seda-inout", "`seda:` with 4 concurrent consumers, InOut request-reply from 4 producer threads"),
    ("cbr", "content-based router (3 Simple `when`/`otherwise` → `setHeader`) + Simple `filter` + `transform`; 1 caller thread"),
    ("splitagg", "JSON order (10 items) → `setHeader` from JsonPath → `split` (JsonPath) → `aggregate` (correlation header, grouped body, completionSize 10); 1 caller thread, unit = orders"),
    ("http", "`netty-http` consumer on 127.0.0.1, small JSON POST, keep-alive, 16 connections from the same std-only load generator"),
];

fn fmt_num(v: f64) -> String {
    let s = format!("{:.0}", v);
    let bytes = s.as_bytes();
    let mut out = String::new();
    for (i, c) in bytes.iter().enumerate() {
        if i > 0 && (bytes.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(*c as char);
    }
    out
}

fn ratio(v: Option<f64>) -> String {
    match v {
        Some(r) if r.is_finite() => format!("{r:.2}x"),
        _ => "-".into(),
    }
}

fn verdict(r: Option<f64>) -> &'static str {
    match r {
        Some(r) if r >= TARGET => "✅ ≥4x",
        Some(r) if r >= 1.0 => "❌ below 4x",
        Some(_) => "❌ slower",
        None => "-",
    }
}

/// Inputs to the report besides the records.
pub struct Context {
    /// `key: value` lines describing the machine and toolchain.
    pub machine: Vec<(String, String)>,
    /// The `BENCH_*` plan used (e.g. "warmup 10 s, 5 x 5 s").
    pub plan: String,
    /// Free text appended under "Analysis" (hand-written profiling notes).
    pub analysis: String,
}

pub fn render(records: &[Record], ctx: &Context) -> String {
    let find = |kind: &str, side: &str, scenario: &str| {
        records
            .iter()
            .rev()
            .find(|r| r.kind == kind && r.get("side") == Some(side) && (scenario.is_empty() || r.get("scenario") == Some(scenario)))
    };
    let mut md = String::new();
    md.push_str("# Benchmarks: Cameleer vs Apache Camel\n\n");
    md.push_str("_Generated by `scripts/bench.sh` (`cameleer-bench report`). Do not edit the tables by hand; re-run the script._\n\n");
    md.push_str("Target set by the owner: Cameleer should be **at least 4x faster** than Apache Camel (Java). (The first target was 3x.)\n\n");

    md.push_str("## Machine and versions\n\n| | |\n|---|---|\n");
    for (k, v) in &ctx.machine {
        md.push_str(&format!("| {k} | {v} |\n"));
    }
    for side in ["rust", "java"] {
        if let Some(r) = find("VERSION", side, "") {
            let v: Vec<String> = r.fields.iter().filter(|(k, _)| *k != "side").map(|(k, v)| format!("{k} {v}")).collect();
            md.push_str(&format!("| {side} runtime | {} |\n", v.join(", ")));
        }
    }

    md.push_str("\n## Methodology\n\n");
    md.push_str(&format!(
        "- Each scenario runs in a fresh process per side, launched by `cameleer-bench measure`. Plan: {}. The warmup is discarded \
         (it also gives the JVM's JIT time to compile the hot paths).\n",
        ctx.plan
    ));
    md.push_str(
        "- Both harnesses use the same closed-loop driver design: N worker threads call the route through a `ProducerTemplate` \
         (`sendBody` / `requestBody`) as fast as they can; every call is timed with a monotonic clock into a per-thread \
         log-linear histogram (64 sub-buckets per power of two, < 1.6% error) with the same layout on both sides. \
         Throughput = completed messages / wall time of the timed iterations.\n\
         - The route ends in a counting processor on both sides (cheaper than `mock:`, which retains exchanges, and than `log:`).\n\
         - Rust: `cargo build --release` (default release profile, no LTO, no PGO). Java: Temurin JDK with default JVM flags \
         (no heap or GC tuning in either direction), Camel's default configuration, plain `DefaultCamelContext`.\n\
         - HTTP: both servers are loaded by the same std-only Rust load generator in `cameleer-bench` running on the same machine \
         (so client and server share the CPUs). Latency there is the client-observed round trip.\n\
         - Memory: peak RSS (Windows peak working set, Linux `ru_maxrss`) of the whole process over the scenario run, read by the \
         parent after the child exits.\n\
         - Startup: wall time from process spawn to the `READY` line printed after `CamelContext.start()` with all benchmark \
         routes (including the HTTP consumer) added; median of 5 runs. For Java this includes JVM startup and class loading.\n\
         - Speedup = rust throughput / java throughput; latency ratio = java p50 (p99) / rust p50 (p99); memory and startup \
         ratios = java / rust. Higher is better for Cameleer everywhere.\n",
    );

    md.push_str("\n## Throughput and latency\n\n");
    md.push_str("| scenario | rust msgs/s | java msgs/s | **speedup** | rust p50 / p99 µs | java p50 / p99 µs | p50 ratio | p99 ratio | 4x target |\n");
    md.push_str("|---|---:|---:|---:|---:|---:|---:|---:|---|\n");
    let mut below = Vec::new();
    for (s, _) in DESCRIPTIONS {
        let (Some(r), Some(j)) = (find("RESULT", "rust", s), find("RESULT", "java", s)) else { continue };
        let rt = r.num("tput").unwrap_or(0.0);
        let jt = j.num("tput").unwrap_or(0.0);
        let speed = (jt > 0.0).then(|| rt / jt);
        let lat = |rec: &Record| match (rec.get("p50_us"), rec.get("p99_us")) {
            (Some(a), Some(b)) if a != "-" => format!("{a} / {b}"),
            _ => "-".into(),
        };
        let lr = |k: &str| match (j.num(k), r.num(k)) {
            (Some(a), Some(b)) if b > 0.0 => Some(a / b),
            _ => None,
        };
        if speed.map_or(true, |v| v < TARGET) {
            below.push((s.to_string(), speed));
        }
        md.push_str(&format!(
            "| {s} | {} | {} | **{}** | {} | {} | {} | {} | {} |\n",
            fmt_num(rt),
            fmt_num(jt),
            ratio(speed),
            lat(r),
            lat(j),
            ratio(lr("p50_us")),
            ratio(lr("p99_us")),
            verdict(speed)
        ));
    }
    md.push_str("\nScenarios:\n\n");
    for (s, d) in DESCRIPTIONS {
        md.push_str(&format!("- **{s}**: {d}.\n"));
    }
    md.push_str("\nThroughput spread across the timed iterations (min – max msgs/s):\n\n| scenario | rust | java |\n|---|---|---|\n");
    for (s, _) in DESCRIPTIONS {
        let spread = |side: &str| {
            find("RESULT", side, s)
                .map(|r| format!("{} – {}", fmt_num(r.num("tput_min").unwrap_or(0.0)), fmt_num(r.num("tput_max").unwrap_or(0.0))))
                .unwrap_or_else(|| "-".into())
        };
        if find("RESULT", "rust", s).is_some() || find("RESULT", "java", s).is_some() {
            md.push_str(&format!("| {s} | {} | {} |\n", spread("rust"), spread("java")));
        }
    }

    md.push_str("\n## Memory (peak RSS)\n\n| scenario | rust MiB | java MiB | java / rust |\n|---|---:|---:|---:|\n");
    let mut scen: Vec<&str> = DESCRIPTIONS.iter().map(|(s, _)| *s).collect();
    scen.push("startup");
    for s in &scen {
        let (Some(r), Some(j)) = (find("RSS", "rust", s), find("RSS", "java", s)) else { continue };
        let rk = r.num("peak_kb").unwrap_or(0.0);
        let jk = j.num("peak_kb").unwrap_or(0.0);
        md.push_str(&format!("| {s} | {:.1} | {:.1} | {} |\n", rk / 1024.0, jk / 1024.0, ratio((rk > 0.0).then(|| jk / rk))));
    }

    md.push_str("\n## Startup\n\n| | rust ms | java ms | java / rust |\n|---|---:|---:|---:|\n");
    if let (Some(r), Some(j)) = (find("STARTUP", "rust", ""), find("STARTUP", "java", "")) {
        let rm = r.num("ms").unwrap_or(0.0);
        let jm = j.num("ms").unwrap_or(0.0);
        md.push_str(&format!(
            "| spawn → context started (median of {}) | {rm:.1} | {jm:.1} | {} |\n",
            r.get("runs").map(|v| v.split(',').count()).unwrap_or(0),
            ratio((rm > 0.0).then(|| jm / rm))
        ));
    }

    md.push_str("\n## Verdict\n\n");
    if below.is_empty() {
        md.push_str("Cameleer reaches the 4x throughput target in every scenario measured.\n");
    } else {
        let list: Vec<String> = below.iter().map(|(s, r)| format!("`{s}` ({})", ratio(*r))).collect();
        md.push_str(&format!(
            "Cameleer does **not** reach the 4x throughput target in: {}. See the analysis below for the measured hot spots \
             and the follow-ups in `docs/STATUS.md`.\n",
            list.join(", ")
        ));
    }
    if !ctx.analysis.trim().is_empty() {
        md.push_str("\n## Analysis\n\n");
        md.push_str(ctx.analysis.trim());
        md.push('\n');
    }
    md.push_str("\n## Reproducing\n\n```sh\nscripts/bench.sh            # Linux, or Git Bash on Windows\n```\n\n```powershell\n.\\scripts\\bench.ps1          # Windows PowerShell (runs bench.sh through Git Bash)\n```\n\n\
`BENCH_QUICK=1` gives a short smoke run; `BENCH_SCENARIOS=\"direct http\"` runs a subset. The script downloads the pinned \
Temurin JDK and Maven, verifies their SHA-256 / SHA-512, and builds the Java side with Maven's strict checksum policy (`-C`). \
Raw records are in `target/bench/results.txt`; the analysis section comes from `benchmarks/analysis.md`.\n");
    md.push_str(FOUND_A_PROBLEM);
    md
}

/// The closing section every documentation page has (the docs harness checks for it).
const FOUND_A_PROBLEM: &str = "\n## Found a problem?\n\n\
If something on this page doesn't match what Cameleer does, or you hit a bug while building\n\
with it, please help fix it, whether you are a person or a coding agent:\n\
[open an issue](https://github.com/pmsudhi/cameleer/issues/new) that describes what you saw,\n\
then fork the repository, fix it, add or update a test, run `cargo test --workspace`, and open\n\
a pull request. [CONTRIBUTING.md](https://github.com/pmsudhi/cameleer/blob/main/CONTRIBUTING.md)\n\
explains the ground rules.\n";

#[cfg(test)]
mod tests {
    use super::*;

    fn recs(lines: &str) -> Vec<Record> {
        lines.lines().filter_map(Record::parse).collect()
    }

    #[test]
    fn renders_ratios_and_verdicts() {
        let r = recs(
            "RESULT side=rust scenario=direct msgs=10 secs=1 tput=4000000 tput_min=1 tput_max=2 mean_us=0.2 p50_us=0.20 p99_us=0.50 max_us=9\n\
             RESULT side=java scenario=direct msgs=10 secs=1 tput=1000000 tput_min=1 tput_max=2 mean_us=0.9 p50_us=0.80 p99_us=2.00 max_us=9\n\
             RESULT side=rust scenario=http msgs=10 secs=1 tput=20000 tput_min=1 tput_max=2 mean_us=1 p50_us=1 p99_us=2 max_us=9\n\
             RESULT side=java scenario=http msgs=10 secs=1 tput=10000 tput_min=1 tput_max=2 mean_us=1 p50_us=1 p99_us=2 max_us=9\n\
             RSS side=rust scenario=direct peak_kb=10240\nRSS side=java scenario=direct peak_kb=204800\n\
             STARTUP side=rust ms=10.0 runs=9,10,11\nSTARTUP side=java ms=800.0 runs=700,800,900\n\
             VERSION side=java camel=4.23.0 java=21.0.13\nnoise line\n",
        );
        let md = render(&r, &Context { machine: vec![("CPU".into(), "x".into())], plan: "p".into(), analysis: "notes".into() });
        assert!(md.contains("| direct | 4,000,000 | 1,000,000 | **4.00x** | 0.20 / 0.50 | 0.80 / 2.00 | 4.00x | 4.00x | ✅ ≥4x |"), "{md}");
        assert!(md.contains("| http | 20,000 | 10,000 | **2.00x**"));
        assert!(md.contains("`http` (2.00x)"));
        assert!(md.contains("| direct | 10.0 | 200.0 | 20.00x |"));
        assert!(md.contains("| 10.0 | 800.0 | 80.00x |"));
        assert!(md.contains("camel 4.23.0, java 21.0.13"));
        assert!(md.contains("## Analysis\n\nnotes"));
        // every docs page ends with the invitation the docs harness checks for
        assert!(md.trim_end().ends_with("explains the ground rules."), "{md}");
        assert!(md.contains("\n## Found a problem?\n"));
    }

    #[test]
    fn formats_thousands() {
        assert_eq!(fmt_num(0.0), "0");
        assert_eq!(fmt_num(999.0), "999");
        assert_eq!(fmt_num(1234567.0), "1,234,567");
    }
}
