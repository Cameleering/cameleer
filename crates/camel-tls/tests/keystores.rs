//! Key store parsing (PKCS#12, JKS, JCEKS, encrypted PKCS#8) against fixtures made by
//! `openssl pkcs12` / `openssl pkcs8` and Java `keytool` (testdata/keystores), round trips
//! through our writers, and using the stores for a TLS server.

use camel_tls::keystore::{KeyStore, KeyStoreFormat};
use camel_tls::{PrivateKey, SslContextParameters, TlsClientConfig, TlsServerConfig, TlsStream};
use std::io::{Read, Write};
use std::net::{TcpListener, TcpStream};
use std::path::PathBuf;
use std::thread;
use std::time::Duration;

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata").join(name)
}

fn read(name: &str) -> Vec<u8> {
    std::fs::read(fixture(name)).unwrap()
}

fn leaf_key() -> PrivateKey {
    PrivateKey::from_pem(&read("leaf.key")).unwrap()
}

fn subject_cn(der: &[u8]) -> String {
    camel_tls::Certificate::from_der(der).unwrap().subject.common_name().unwrap_or("").to_string()
}

fn same_key(a: &PrivateKey, b: &PrivateKey) -> bool {
    a.public_key().same_as(&b.public_key())
}

#[test]
fn openssl_pkcs12_modern_and_legacy() {
    for f in ["keystores/openssl_modern.p12", "keystores/openssl_legacy.p12", "keystores/openssl_aes128_sha1mac.p12"] {
        let data = read(f);
        assert_eq!(KeyStoreFormat::detect(&data), KeyStoreFormat::Pkcs12, "{f}");
        let ks = KeyStore::load(&data, Some("changeit"), None).unwrap_or_else(|e| panic!("{f}: {e}"));
        let (key, chain) = ks.key_entry(Some("server")).unwrap_or_else(|| panic!("{f}: no 'server' entry: {:?}", ks.aliases()));
        assert!(same_key(key, &leaf_key()), "{f}");
        assert_eq!(subject_cn(&chain[0]), "leaf.camel.test");
        if !f.contains("aes128") {
            assert_eq!(chain.len(), 3, "{f}: chain leaf, intermediate, root");
            assert_eq!(subject_cn(&chain[1]), "Camel Test Intermediate");
        }
        let e = KeyStore::load(&data, Some("wrong"), None).unwrap_err();
        assert!(e.contains("password"), "{f}: {e}");
    }
    let ts = KeyStore::load(&read("keystores/openssl_trust.p12"), Some("changeit"), None).unwrap();
    assert_eq!(ts.trusted_certs().len(), 1);
    assert!(ts.key_entry(None).is_none());
}

#[test]
fn keytool_stores() {
    // JKS / JCEKS with a separate key password, imported from the OpenSSL PKCS#12
    for f in ["keystores/keytool.jks", "keystores/keytool.jceks"] {
        let data = read(f);
        let ks = KeyStore::load(&data, Some("changeit"), Some("keypass")).unwrap_or_else(|e| panic!("{f}: {e}"));
        let (key, chain) = ks.key_entry(Some("server")).unwrap();
        assert!(same_key(key, &leaf_key()));
        assert_eq!(chain.len(), 3);
        assert!(KeyStore::load(&data, Some("changeit"), Some("nope")).is_err());
        let e = KeyStore::load(&data, Some("wrong"), Some("keypass")).unwrap_err();
        assert!(e.contains("password"), "{e}");
    }
    let ts = KeyStore::load(&read("keystores/keytool_trust.jks"), None, None).unwrap();
    assert_eq!(subject_cn(&ts.trusted_certs()[0]), "Camel Test Root CA");
    let ts = KeyStore::load(&read("keystores/keytool_trust.p12"), Some("changeit"), None).unwrap();
    assert_eq!(subject_cn(&ts.trusted_certs()[0]), "Camel Test Root CA");
    // keys generated by keytool (Java PKCS#12 = PBES2/AES-256/HmacSHA256)
    let ec = KeyStore::load(&read("keystores/keytool_ec.p12"), Some("changeit"), None).unwrap();
    assert!(matches!(ec.key_entry(Some("server")).unwrap().0, PrivateKey::Ec { .. }));
    let rsa = KeyStore::load(&read("keystores/keytool_rsa.jks"), Some("changeit"), None).unwrap();
    assert!(matches!(rsa.key_entry(Some("rsaserver")).unwrap().0, PrivateKey::Rsa(_)));
    let ed = KeyStore::load(&read("keystores/keytool_ed25519.p12"), Some("changeit"), None).unwrap();
    assert!(matches!(ed.key_entry(Some("ed")).unwrap().0, PrivateKey::Ed25519 { .. }));
}

#[test]
fn encrypted_pkcs8_pem() {
    for f in ["leaf_pbes2_aes256.key", "leaf_pbes2_sha1_aes128.key", "leaf_pbes2_des3.key", "leaf_pbe_sha1_3des.key"] {
        let data = read(&format!("keystores/{f}"));
        assert!(PrivateKey::from_pem(&data).unwrap_err().contains("password"));
        let k = PrivateKey::from_pem_with_password(&data, Some("secret")).unwrap_or_else(|e| panic!("{f}: {e}"));
        assert!(same_key(&k, &leaf_key()), "{f}");
        assert!(PrivateKey::from_pem_with_password(&data, Some("wrong")).is_err());
    }
}

#[test]
fn writer_round_trips() {
    let id = camel_tls::self_signed("localhost");
    let rsa = PrivateKey::from_pem(&read("rsa2048.pkcs8.pem")).unwrap();
    let rsa_cert = camel_tls::pem::parse_pem(&read("rsa_selfsigned.pem")).unwrap().remove(0).der;
    let ed = camel_tls::certgen::issue(&camel_tls::certgen::CertParams::server(&["ed.test"]), PrivateKey::generate_ed25519(), None);
    let ks = KeyStore::from_key_entry("ec", id.key.clone(), vec![id.cert_der.clone()])
        .add_key("rsa", rsa.clone(), vec![rsa_cert.clone()])
        .add_key("ed", ed.key.clone(), vec![ed.cert_der.clone()])
        .add_cert("trusted", rsa_cert.clone());
    for (name, bytes, kp) in [
        ("pkcs12", ks.to_pkcs12("s3cret"), "s3cret"),
        ("legacy pkcs12", camel_tls::keystore::pkcs12::write(&ks, "s3cret", camel_tls::keystore::pkcs12::Pkcs12Profile::Legacy), "s3cret"),
        ("jks", ks.to_jks("s3cret", "kp"), "kp"),
    ] {
        let back = KeyStore::load(&bytes, Some("s3cret"), Some(kp)).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert!(same_key(back.key_entry(Some("ec")).unwrap().0, &id.key), "{name}");
        assert!(same_key(back.key_entry(Some("rsa")).unwrap().0, &rsa), "{name}");
        assert!(same_key(back.key_entry(Some("ed")).unwrap().0, &ed.key), "{name}");
        assert_eq!(back.trusted_certs(), vec![rsa_cert.clone()], "{name}");
    }
    // encrypted PKCS#8 round trip
    let enc = camel_tls::pbe::encrypt_private_key_info(&id.key.to_pkcs8(), "pw");
    let pem = camel_tls::pem::encode_pem("ENCRYPTED PRIVATE KEY", &enc);
    assert!(same_key(&PrivateKey::from_pem_with_password(pem.as_bytes(), Some("pw")).unwrap(), &id.key));
}

fn serve_once(cfg: TlsServerConfig) -> (u16, thread::JoinHandle<()>) {
    let l = TcpListener::bind("127.0.0.1:0").unwrap();
    let port = l.local_addr().unwrap().port();
    let h = thread::spawn(move || {
        let (s, _) = l.accept().unwrap();
        s.set_read_timeout(Some(Duration::from_secs(10))).unwrap();
        let mut t = TlsStream::accept(s, &cfg).unwrap();
        let mut b = [0u8; 4];
        t.read_exact(&mut b).unwrap();
        t.write_all(&b).unwrap();
        let _ = t.close();
    });
    (port, h)
}

#[test]
fn key_stores_drive_tls_servers() {
    // openssl PKCS#12 (chain leaf.camel.test <- intermediate <- root), trusted through a JKS trust store
    let cases = [
        (SslContextParameters::new().key_store(fixture("keystores/openssl_modern.p12"), "changeit"), "leaf.camel.test"),
        (SslContextParameters::new().key_store(fixture("keystores/keytool.jks"), "changeit").key_password("keypass").cert_alias("server"), "leaf.camel.test"),
        (SslContextParameters::new().key_store(fixture("keystores/openssl_legacy.p12"), "changeit"), "leaf.camel.test"),
    ];
    let client = SslContextParameters::new().trust_store(fixture("keystores/keytool_trust.jks"), Some("changeit")).client_config().unwrap();
    for (server, host) in cases {
        let (port, h) = serve_once(server.server_config().unwrap());
        let s = TcpStream::connect(("127.0.0.1", port)).unwrap();
        let mut t = TlsStream::connect(s, host, &client).unwrap();
        t.write_all(b"ping").unwrap();
        let mut b = [0u8; 4];
        t.read_exact(&mut b).unwrap();
        assert_eq!(&b, b"ping");
        h.join().unwrap();
    }
    // keytool-generated Ed25519 key: TLS 1.3 with an Ed25519 certificate
    let server = SslContextParameters::new().key_store(fixture("keystores/keytool_ed25519.p12"), "changeit");
    let ck = server.key_material().unwrap().unwrap();
    let (port, h) = serve_once(server.server_config().unwrap());
    let client = TlsClientConfig::builder().system_roots(false).add_root_der(&ck.chain[0]).unwrap().build();
    let s = TcpStream::connect(("127.0.0.1", port)).unwrap();
    let mut t = TlsStream::connect(s, "localhost", &client).unwrap();
    t.write_all(b"ed25").unwrap();
    let mut b = [0u8; 4];
    t.read_exact(&mut b).unwrap();
    h.join().unwrap();
}

#[test]
fn wrong_store_password_is_a_config_error() {
    let e = SslContextParameters::new().key_store(fixture("keystores/openssl_modern.p12"), "nope").server_config().unwrap_err();
    assert!(e.to_string().contains("password"), "{e}");
    let e = SslContextParameters::new().key_store(fixture("keystores/openssl_modern.p12"), "changeit").cert_alias("missing").server_config().unwrap_err();
    assert!(e.to_string().contains("missing"), "{e}");
}

/// Our JKS and PKCS#12 output is readable by Java's keytool (skipped without a JDK).
#[test]
fn keytool_reads_our_stores() {
    if std::process::Command::new("keytool").arg("-help").output().is_err() {
        eprintln!("keytool not found: skipping");
        return;
    }
    let dir = std::env::temp_dir().join(format!("camel-tls-ks-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let id = camel_tls::self_signed("localhost");
    let ks = KeyStore::from_key_entry("mykey", id.key.clone(), vec![id.cert_der.clone()]);
    for (file, typ, bytes) in [("a.p12", "PKCS12", ks.to_pkcs12("changeit")), ("a.jks", "JKS", ks.to_jks("changeit", "changeit"))] {
        let p = dir.join(file);
        std::fs::write(&p, bytes).unwrap();
        let out = std::process::Command::new("keytool")
            .args(["-list", "-keystore", p.to_str().unwrap(), "-storepass", "changeit", "-storetype", typ])
            .output()
            .unwrap();
        let text = String::from_utf8_lossy(&out.stdout);
        assert!(out.status.success() && text.contains("mykey") && text.contains("PrivateKeyEntry"), "{typ}: {text} {}", String::from_utf8_lossy(&out.stderr));
    }
    let _ = std::fs::remove_dir_all(&dir);
}
